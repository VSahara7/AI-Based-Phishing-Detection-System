for name, model in models.items():

    y_pred = model.predict(X_test)

    # Score for ranking metrics
    y_score = get_scores(model, X_test)

    tn, fp, fn, tp = confusion_matrix(
        y_test,
        y_pred
    ).ravel()

    specificity = tn / (tn + fp)

    # -------------------------------------------------
    # Probability-based log loss
    # -------------------------------------------------

    if hasattr(model, "predict_proba"):

        y_proba = model.predict_proba(
            X_test
        )[:, 1]

        model_log_loss = log_loss(
            y_test,
            y_proba
        )

    else:

        # LinearSVC does not provide calibrated
        # probabilities, therefore log loss is not
        # reported for this model.

        model_log_loss = np.nan

    # -------------------------------------------------
    # Metrics
    # -------------------------------------------------

    rows.append({

        "Model": name,

        "Accuracy":
            accuracy_score(
                y_test,
                y_pred
            ),

        "Precision":
            precision_score(
                y_test,
                y_pred
            ),

        "Recall (Sensitivity)":
            recall_score(
                y_test,
                y_pred
            ),

        "Specificity":
            specificity,

        "F1-Score":
            f1_score(
                y_test,
                y_pred
            ),

        "Balanced Accuracy":
            balanced_accuracy_score(
                y_test,
                y_pred
            ),

        "Matthews Corr. Coef.":
            matthews_corrcoef(
                y_test,
                y_pred
            ),

        "Cohen's Kappa":
            cohen_kappa_score(
                y_test,
                y_pred
            ),    
                
        "ROC-AUC":
        roc_auc_score(
            y_test,
            y_score
        ),

        "Log Loss":
            model_log_loss,
            
        "PR-AUC (Average Precision)":
        average_precision_score(
            y_test,
            y_score
        )

    })

