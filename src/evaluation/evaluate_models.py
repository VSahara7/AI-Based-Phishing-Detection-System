print("\nGenerating Logistic Regression Accuracy + Loss Curves...")

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression

# -----------------------------------------------------
# Create validation data from the training partition.
# The final held-out test set remains untouched.
# -----------------------------------------------------

X_fit, X_val, y_fit, y_val = train_test_split(
    X_train,
    y_train,
    test_size=0.2,
    stratify=y_train,
    random_state=RANDOM_STATE
)

# -----------------------------------------------------
# Iterative Logistic Regression diagnostic
#
# The final saved LogisticRegression model is NOT changed.
# This diagnostic uses the same Logistic Regression family
# and the same TF-IDF representation, but records its
# optimisation progress across repeated iterations.
# -----------------------------------------------------

diagnostic_lr = LogisticRegression(
    solver="saga",
    penalty="l2",
    C=1.0,
    max_iter=1,
    warm_start=True,
    random_state=RANDOM_STATE
)

n_epochs = 30

train_accuracy_history = []
validation_accuracy_history = []
train_loss_history = []
validation_loss_history = []

# -----------------------------------------------------
# Repeat one optimisation iteration at a time
# -----------------------------------------------------

for epoch in range(n_epochs):

    diagnostic_lr.fit(X_fit, y_fit)

    # Predictions for accuracy
    train_pred = diagnostic_lr.predict(X_fit)
    validation_pred = diagnostic_lr.predict(X_val)

    # Probabilities for log loss
    train_probability = diagnostic_lr.predict_proba(X_fit)[:, 1]
    validation_probability = diagnostic_lr.predict_proba(X_val)[:, 1]

    train_accuracy_history.append(
        accuracy_score(y_fit, train_pred)
    )

    validation_accuracy_history.append(
        accuracy_score(y_val, validation_pred)
    )

    train_loss_history.append(
        log_loss(y_fit, train_probability)
    )

    validation_loss_history.append(
        log_loss(y_val, validation_probability)
    )

# -----------------------------------------------------
# Save the recorded training history
# -----------------------------------------------------

training_history = pd.DataFrame({
    "Epoch": range(1, n_epochs + 1),
    "Training Accuracy": train_accuracy_history,
    "Validation Accuracy": validation_accuracy_history,
    "Training Loss": train_loss_history,
    "Validation Loss": validation_loss_history
})

training_history.to_csv(
    OUT_DIR / "logistic_training_accuracy_loss_history.csv",
    index=False
)

